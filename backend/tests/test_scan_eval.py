SCAN_TARGET_NAMES = {
    "scan_trace",
    "scan_visual_match",
    "scan_tables",
    "scan_lineweights",
    "scan_primitive_quality",
    "scan_noise",
}


def _scan_ir(promoted: bool = True) -> DrawingIR:
    entities = [
        RectangleEntity(
            id="scan_sheet_border",
            layer="sheet",
            x=0,
            y=0,
            width=420,
            height=297,
            group="sheet",
            stroke_width=0.35,
        ),
        RectangleEntity(
            id="scan_drawing_frame",
            layer="sheet",
            x=10,
            y=10,
            width=400,
            height=277,
            group="sheet",
            stroke_width=0.25,
        ),
    ]
    entities.extend(
        PolylineEntity(
            id=f"ref_trace_{index:05d}",
            layer="reference_trace",
            points=[[index * 0.1, 0], [index * 0.1 + 4, 1]],
            group="reference_trace",
            stroke_width=0.1,
        )
        for index in range(70)
    )
    entities.extend(
        PolylineEntity(
            id=f"editable_line_{index:05d}",
            layer="editable_linework",
            points=[[index * 0.2, 20], [index * 0.2 + 10, 20]],
            group="editable_linework",
            stroke_width=0.28,
        )
        for index in range(80)
    )
    entities.extend(
        LineEntity(
            id=f"table_grid_{index:03d}",
            layer="table",
            x1=index,
            y1=200,
            x2=index,
            y2=240,
            group="title_block" if index < 5 else "parameter_table",
            tags=["grid"],
            stroke_width=0.18,
        )
        for index in range(12)
    )
    if promoted:
        entities.extend(
            LineEntity(
                id=f"promoted_line_{index:05d}",
                layer="promoted_geometry",
                x1=index,
                y1=40,
                x2=index + 10,
                y2=40,
                group="promoted_geometry",
                stroke_width=0.35,
            )
            for index in range(10)
        )
        entities.append(
            CircleEntity(
                id="promoted_circle_00000",
                layer="promoted_geometry",
                cx=120,
                cy=90,
                r=12,
                group="promoted_geometry",
                stroke_width=0.35,
            )
        )
        entities.extend(
            [
                LineEntity(
                    id="promoted_arrow_00000",
                    layer="promoted_geometry",
                    x1=140,
                    y1=90,
                    x2=136,
                    y2=92,
                    group="promoted_geometry",
                    tags=["dimension_arrow", "arrowhead"],
                    stroke_width=0.25,
                ),
                LineEntity(
                    id="promoted_arrow_00001",
                    layer="promoted_geometry",
                    x1=140,
                    y1=90,
                    x2=136,
                    y2=88,
                    group="promoted_geometry",
                    tags=["dimension_arrow", "arrowhead"],
                    stroke_width=0.25,
                ),
            ]
        )

    return DrawingIR(
        units="mm",
        layers=[
            Layer(name="sheet", color="gray"),
            Layer(name="reference_trace", color="gray"),
            Layer(name="editable_linework", color="white"),
            Layer(name="table", color="white"),
            Layer(name="promoted_geometry", color="white"),
        ],
        entities=entities,
        notes=["Scan CAD baseline generated by external vectorizers."],
    )


def _source_image_from_ir(tmp_path, ir: DrawingIR):
    mask = _rasterize_ir_to_mask(ir, 1000, 700)
    image = np.full(mask.shape, 255, dtype=np.uint8)
    image[mask > 0] = 0
    path = tmp_path / "source.png"
    cv2.imwrite(str(path), image)
    return path


def test_scan_eval_scores_pipeline_output_full_marks(tmp_path):
    ir = _scan_ir(promoted=True)
    report = evaluate_scan_structure(ir, _source_image_from_ir(tmp_path, ir))
    assert report.passed is True
    assert report.overall_score == 1.0
    assert {target.name for target in report.targets} == SCAN_TARGET_NAMES
    assert all(target.passed for target in report.targets)


def test_scan_eval_without_promotion_is_not_penalized_like_template_eval(tmp_path):
    ir = _scan_ir(promoted=False)
    report = evaluate_scan_structure(ir, _source_image_from_ir(tmp_path, ir))
    promotion = next(target for target in report.targets if target.name == "scan_primitive_quality")
    assert report.passed is False
    assert 0.75 <= report.overall_score < 1.0
    assert promotion.score < 1.0
    assert "has promoted primitive layer" in promotion.missing


def test_scan_lineweights_ignore_title_block_text_entities(tmp_path):
    ir = _scan_ir(promoted=True)
    ir.entities.extend(
        TextEntity(
            id=f"title_block_text_{index}",
            layer="text",
            x=260 + index,
            y=40,
            text="标题",
            height=1.2,
            group="title_block",
            tags=["title_block", "ocr_text"],
        )
        for index in range(40)
    )

    report = evaluate_scan_structure(ir, _source_image_from_ir(tmp_path, ir))
    lineweights = next(target for target in report.targets if target.name == "scan_lineweights")

    assert "table grid is readable" not in lineweights.missing
    assert lineweights.evidence["table_avg_mm"] == 0.18


def test_empty_scan_eval_reports_missing_pipeline_stages():
    report = evaluate_scan_structure(DrawingIR())
    assert report.passed is False
    assert report.overall_score < 0.35
    assert all(target.missing for target in report.targets)


def test_scan_visual_match_reports_missing_and_unreadable_sources(tmp_path):
    missing = evaluate_scan_structure(_scan_ir(), tmp_path / "missing.png")
    missing_visual = next(target for target in missing.targets if target.name == "scan_visual_match")
    assert missing_visual.score == 0.0
    assert missing_visual.evidence["source"] == "missing"

    bad_path = tmp_path / "bad.png"
    bad_path.write_text("not an image", encoding="utf-8")
    unreadable = evaluate_scan_structure(_scan_ir(), bad_path)
    unreadable_visual = next(target for target in unreadable.targets if target.name == "scan_visual_match")
    assert unreadable_visual.score == 0.0
    assert unreadable_visual.evidence["source"] == "unreadable"


def test_scan_eval_geometry_helper_edges_are_covered():
    open_polyline = PolylineEntity(id="open", layer="reference_trace", points=[[0, 0]], group="reference_trace")
    closed_polyline = PolylineEntity(
        id="closed",
        layer="reference_trace",
        points=[[0, 0], [3, 0], [3, 4]],
        closed=True,
        group="reference_trace",
    )
    arc = ArcEntity(id="arc", layer="geometry", cx=5, cy=5, r=2, start_angle=0, end_angle=180)
    rectangle = RectangleEntity(id="rect", layer="sheet", x=1, y=2, width=3, height=4)
    text = TextEntity(id="text", layer="text", x=0, y=0, text="ignored")

    assert _entity_length(open_polyline) == 0.0
    assert math.isclose(_entity_length(closed_polyline), 12.0)
    assert math.isclose(_entity_length(arc), math.pi * 2)
    assert _entity_length(rectangle) == 14
    assert _entity_length(text) == 0.0

    large = np.zeros((2400, 1200), dtype=np.uint8)
    resized = _resize_for_quality(large)
    assert max(resized.shape) == 1200

    empty_metrics = _mask_similarity(np.zeros((20, 20), dtype=np.uint8), np.zeros((20, 20), dtype=np.uint8))
    assert empty_metrics["edge_fscore"] == 0.0


def test_scan_eval_raster_bounds_without_sheet_cover_all_geometry():
    ir = DrawingIR(
        entities=[
            LineEntity(id="line", layer="geometry", x1=0, y1=0, x2=10, y2=0),
            PolylineEntity(id="poly", layer="geometry", points=[[1, 1], [2, 3]]),
            CircleEntity(id="circle", layer="geometry", cx=20, cy=10, r=5),
            ArcEntity(id="arc", layer="geometry", cx=-4, cy=-3, r=2, start_angle=0, end_angle=90),
            RectangleEntity(id="rect", layer="geometry", x=30, y=20, width=8, height=4),
        ]
    )
    assert _canvas_bounds(ir) == (-6, -5, 38, 24)
    assert _canvas_bounds(DrawingIR()) == (0, 0, 100, 100)
    assert _rasterize_ir_to_mask(ir, 240, 180).sum() > 0
